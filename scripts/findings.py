"""Write bugs/FINDINGS.md from the bug records, grouped by severity and then by area.

The records are simple enough that a line reader is used instead of a YAML library, so the script runs with the standard library only.
"""
import glob
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = ["high", "medium", "low"]


def read_record(path):
    rec = {}
    key = None
    for line in open(path):
        if line[:1] not in (" ", "\n") and ":" in line:
            key, _, value = line.partition(":")
            rec[key] = value.strip()
        elif key and line.strip():
            rec[key] = (rec[key].rstrip(">").strip() + " " + line.strip()).strip()
    return rec


def main():
    recs = [read_record(p) for p in sorted(glob.glob(os.path.join(ROOT, "bugs", "*.yaml")))]
    recs.sort(key=lambda r: (ORDER.index(r["severity"]), r["area"], r["id"]))
    counts = {s: sum(r["severity"] == s for r in recs) for s in ORDER}
    areas = sorted({r["area"] for r in recs})
    out = [
        "# Findings",
        "",
        f"This file lists the {len(recs)} bug records in this directory, generated by `scripts/findings.py`. Every record is a property that was refuted on the Lean model and then confirmed on NumPy 2.5.4. Each one has a reproducer in `repro/` that prints `REPRODUCED`, and `scripts/check_bugs.py` reruns all of them. Behaviour that the NumPy documentation already warns about is recorded as a refuted property in the Lean files and is not listed here.",
        "",
        f"By severity there are {counts['high']} high, {counts['medium']} medium and {counts['low']} low records. By area the counts are " + ", ".join(f"{a} {sum(r['area'] == a for r in recs)}" for a in areas) + ".",
        "",
        "None of these has been reported to NumPy, and the `upstream` field of each record says whether an existing issue was searched for.",
    ]
    for sev in ORDER:
        group = [r for r in recs if r["severity"] == sev]
        if not group:
            continue
        out += ["", f"## {sev.capitalize()} severity", "", "| Record | Area | Kind | What goes wrong |", "| --- | --- | --- | --- |"]
        for r in group:
            out.append(f"| [{r['id']}]({r['id']}.yaml) ([repro](repro/{r['id']}.py)) | {r['area']} | {r['kind']} | {r['title']} |")
    open(os.path.join(ROOT, "bugs", "FINDINGS.md"), "w").write("\n".join(out) + "\n")
    print(f"wrote {len(recs)} records")


if __name__ == "__main__":
    main()
